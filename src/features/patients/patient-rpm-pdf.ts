import { dateFormatter, translate as t } from '@/i18n'
import { measurement, readingLabel, readingTimestamp } from '@/features/device-readings/readings'
import { bloodPressurePdfReport } from '@/features/reports/blood-pressure-pdf'
import { glucosePdfReport } from '@/features/reports/glucose-pdf'
import { pulseOximetryPdfReport } from '@/features/reports/pulse-oximetry-pdf'
import { parseGlucose } from '@/features/reports/glucose-readings'
import { parseOximetry } from '@/features/reports/oximetry-readings'
import { parsePressure } from '@/features/reports/pressure-readings'
import { createMonitoringPdfDocument, type MonitoringPdf } from '@/features/reports/monitoring-pdf'
import type { PatientRecord } from '@/services/patient-services/patient-services'
import type { DeviceReading } from '@/services/reading-services/reading-services'
import type { NoteLine } from './report-notes'
import { patientAge, patientName } from './patients'

export interface PatientReadingGroup {
  type: string
  model?: string
  imei?: string
  readings: DeviceReading[]
}

interface PatientRpmReport {
  patient: PatientRecord
  generatedBy?: string
  generatedAt: Date
  from: string
  to: string
  devices: string[]
  groups: PatientReadingGroup[]
  notes: NoteLine[]
}

const missing = '—'
const date = dateFormatter({ dateStyle: 'medium', timeZone: 'UTC' })
const timestamp = dateFormatter({ dateStyle: 'medium', timeStyle: 'short' })

export async function createPatientRpmPdf(report: PatientRpmReport, logo: ArrayBuffer) {
  const { patient, generatedBy, generatedAt, from, to, devices, groups, notes } = report
  const name = patientName(patient)
  const birthDate = patient.dob?.slice(0, 10)
  const birth = birthDate ? new Date(birthDate) : null
  const age = patientAge(birthDate, generatedAt)
  const sex = patient.gender?.trim().replace(/^./u, (letter) => letter.toLocaleUpperCase())
  const dateRange = `${date.format(new Date(from))} - ${date.format(new Date(to))}`
  const pdf = await createMonitoringPdfDocument(t('RPM Report'), logo)
  const total = groups.reduce((count, group) => count + group.readings.length, 0)

  pdf.addOverview(
    [
      [t('Patient name'), name],
      [t('MRN'), patient.mrn?.trim() || missing],
      [
        t('Date of birth'),
        birth && Number.isFinite(birth.getTime()) ? date.format(birth) : missing,
      ],
      [t('Age'), age == null ? missing : String(age)],
      [t('Sex'), sex || missing],
      [t('Generated by'), generatedBy || missing],
      [t('Date range'), dateRange],
      [t('Generated on'), timestamp.format(generatedAt)],
    ],
    [
      [
        t('Devices'),
        devices.length
          ? devices.map((device, index) => `${index + 1}. ${device}`).join('\n')
          : t('No devices assigned'),
      ],
      [t('Reading Count'), total ? String(total) : t('No readings in this date range')],
    ],
    notes.length ? [{ title: t("Doctor's Notes"), lines: notes }] : [],
  )

  for (const { type, model, imei, readings } of groups) {
    const label = t(readingLabel(type))
    const device = model || t('Device')
    let remaining = readings

    function addVital<Reading extends { timestamp: number }>(
      parsed: (NoInfer<Reading> & { id: string })[],
      build: (
        patient: { id: string; name: string; device: string; readings: Reading[] },
        total: number,
      ) => MonitoringPdf<Reading>,
    ) {
      if (!parsed.length) return
      const charted = new Set(parsed.map((reading) => reading.id))
      const uncharted = readings
        .filter((reading) => !charted.has(reading.id))
        .map((reading) => {
          const { value, secondary } = measurement(reading)
          return {
            timestamp: readingTimestamp(reading, 'recorded'),
            value,
            context: secondary ?? missing,
          }
        })
      pdf.addReport(build({ id: patient.id, name, device, readings: parsed }, readings.length), {
        range: dateRange,
        imei,
        uncharted,
      })
      remaining = []
    }

    if (type === 'blood_pressure') addVital(parsePressure(readings), bloodPressurePdfReport)
    if (type === 'blood_glucose') addVital(parseGlucose(readings), glucosePdfReport)
    if (type === 'pulse_ox') addVital(parseOximetry(readings), pulseOximetryPdfReport)

    if (remaining.length) {
      pdf.addReadingTable(
        label,
        { model: device, range: dateRange, imei },
        remaining
          .map((reading) => {
            const { value, unit, secondary } = measurement(reading)
            return {
              timestamp: readingTimestamp(reading, 'recorded'),
              measurement: [unit ? `${value} ${unit}` : value, secondary]
                .filter(Boolean)
                .join(' · '),
            }
          })
          .sort((a, b) => (b.timestamp ?? -Infinity) - (a.timestamp ?? -Infinity)),
      )
    }
  }
  const mrn = patient.mrn?.trim()
  return pdf.save(dateRange, mrn ? `${name} · ${t('MRN')} ${mrn}` : name)
}
